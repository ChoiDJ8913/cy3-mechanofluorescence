function phi2 = DihedralAngle( X, Y, Z );
% https://en.wikipedia.org/wiki/Dihedral_angle
% phi2 is the dihedral angle at C2 - C3 bond.
% u1 = C2 - C1 
% u2 = C3 - C2
% u3 = C4 - C3
s = 2;
u1 = [ X(s) Y(s) Z(s) ] - [ X(s-1) Y(s-1) Z(s-1) ];
u2 = [ X(s+1) Y(s+1) Z(s+1) ] - [ X(s) Y(s) Z(s) ];
u3 = [ X(s+2) Y(s+2) Z(s+2) ] - [ X(s+1) Y(s+1) Z(s+1) ];
%dot( u2, cross( cross( u1, u2 ), cross( u2, u3 ) ) )
%norm(u2) * dot( cross( u1, u2 ), cross( u2, u3 ) )
phi2 = atan2( dot( u2, cross( cross( u1, u2 ), cross( u2, u3 ) ) ), norm(u2) * dot( cross( u1, u2 ), cross( u2, u3 ) ) );
return;

function [ X1 Y1 Z1 ] = Rotation( X, Y, Z, theta );
X1 = X;
Y1 = Y;
Z1 = Z;
C2 = [ X(3) Y(3) Z(3) ];
C3 = [ X(4) Y(4) Z(4) ];
% Rotation Axis = C2 -> C3 vector
a = C3(1)-C2(1);
b = C3(2)-C2(2);
c = C3(3)-C2(3);
for i = 4:7
	xi = X(i)-C2(1);
	yi = Y(i)-C2(2);
	zi = Z(i)-C2(3);


	% Rodrigues' rotation formula
    % unit vector of the rotation axis (a, b, c)
    axis_length = sqrt(a^2 + b^2 + c^2);
    kx = a / axis_length;
    ky = b / axis_length;
    kz = c / axis_length;
    
    % point to rotate, vector (x, y, z)
    v = [xi; yi; zi];
    
    % Rodrigues rotation formula
    % compute the rotated vector
    v_rot = v * cos(theta) + cross([kx; ky; kz], v) * sin(theta) + ...
            [kx; ky; kz] * (dot([kx; ky; kz], v)) * (1 - cos(theta));
    
    % return the result vector
	X1(i) = v_rot(1) + C2(1);
	Y1(i) = v_rot(2) + C2(2);
	Z1(i) = v_rot(3) + C2(3);
end

